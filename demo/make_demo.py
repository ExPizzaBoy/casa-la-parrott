#!/usr/bin/env python3
"""Writes sample calendars (dated relative to today) so you can preview the hub.

    python demo/make_demo.py && python build.py demo/config.yml

demo/config.yml is generated from ../config.yml with each ${CAL_X} secret
swapped for a local x.ics file, so the demo always matches your real settings.
"""
import datetime as dt
import re
from pathlib import Path

HERE = Path(__file__).parent
today = dt.date.today()


def stamp(day_offset, hhmm):
    d = today + dt.timedelta(days=day_offset)
    return d.strftime("%Y%m%d") + "T" + hhmm.replace(":", "") + "00"


def ev(uid, title, start, end=None, desc="", loc="", rrule="", all_day=False):
    lines = ["BEGIN:VEVENT", f"UID:{uid}@demo", f"SUMMARY:{title}"]
    if all_day:
        d = today + dt.timedelta(days=start)
        lines += [f"DTSTART;VALUE=DATE:{d:%Y%m%d}", f"DTEND;VALUE=DATE:{d + dt.timedelta(days=end or 1):%Y%m%d}"]
    else:
        lines += [f"DTSTART:{stamp(*start)}", f"DTEND:{stamp(*end)}"]
    if rrule:
        lines.append(f"RRULE:{rrule}")
    if desc:
        lines.append("DESCRIPTION:" + desc.replace("\n", "\\n").replace(",", "\\,"))
    if loc:
        lines.append("LOCATION:" + loc.replace(",", "\\,"))
    lines.append("END:VEVENT")
    return "\n".join(lines)


def write(name, *events):
    body = "\n".join(["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//family-hub demo//EN", *events, "END:VCALENDAR"])
    (HERE / f"{name}.ics").write_text(body.replace("\n", "\r\n") + "\r\n")


for old in HERE.glob("*.ics"):
    old.unlink()

write("mom",
      ev("m1", "Dentist", (1, "08:00"), (1, "09:00"), loc="Smile Dental"),
      ev("m2", "Book club", (3, "19:00"), (3, "21:00")))
write("mom_work",
      ev("mw1", "Budget meeting", (0, "13:00"), (0, "14:00")),          # hidden (work)
      ev("mw2", "Working late", (3, "17:00"), (3, "19:30")),
      ev("mw3", "Staff meeting", (1, "10:00"), (1, "11:00"), rrule="FREQ=WEEKLY;COUNT=6"))
write("dad",
      ev("d1", "Oil change", (2, "07:30"), (2, "08:30")))
write("dad_work",
      ev("dw1", "Quarterly review", (0, "10:00"), (0, "11:00")),        # hidden (work)
      ev("dw2", "Working late - release night", (0, "17:00"), (0, "20:00")),
      ev("dw3", "Team standup", (1, "09:00"), (1, "09:15"), rrule="FREQ=DAILY;COUNT=10"))
write("piper",
      ev("p1", "Volleyball practice", (0, "17:30"), (0, "19:30"), loc="High school gym",
         rrule="FREQ=WEEKLY;BYDAY=MO,TU,TH;COUNT=12"),
      ev("p2", "Volleyball match vs. East", (2, "18:00"), (2, "20:00"), loc="East High School",
         desc="Away match - bus leaves 4:45\nPack: Away jersey"),
      ev("p3", "Club volleyball tournament", (5, "07:30"), (5, "17:00"), loc="DeVos Place",
         desc="Pack: Folding chair, Cooler"),
      ev("p4", "Half day - early release", 4, all_day=True))
write("paige",
      ev("pg1", "BIO 201 lecture", (0, "09:00"), (0, "10:15"), rrule="FREQ=WEEKLY;BYDAY=MO,WE,FR;COUNT=20"),  # hidden
      ev("pg2", "Study group", (1, "19:00"), (1, "21:00")),                                                 # hidden
      ev("pg3", "Paige home for Thanksgiving break", 23, end=5, all_day=True),
      ev("pg4", "Paige home for winter break", 45, end=10, all_day=True))
write("family",
      ev("f1", "Grandma's birthday dinner", (9, "18:00"), (9, "20:30"), loc="Grandma's house"),
      ev("f2", "Pizza night", (4, "18:00"), (4, "19:00")))

# demo/config.yml = ../config.yml with secrets pointing at the files above
cfg = (HERE.parent / "config.yml").read_text()
cfg = re.sub(r"\$\{CAL_([A-Z0-9_]+)\}", lambda m: f"{m.group(1).lower()}.ics", cfg)
(HERE / "config.yml").write_text("# GENERATED by make_demo.py from ../config.yml - edit that file instead.\n" + cfg)
print("Demo calendars written to", HERE)
